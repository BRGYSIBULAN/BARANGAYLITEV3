/**
 * Purpose: attach one content-derived release token to every local browser CSS/JS reference.
 * Depends on: checked-in HTML, assets/js modules, vendor JavaScript, and the central stylesheet.
 * Debug: run `npm run version:assets`; `npm run check` reports any stale or missing token.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const TOKEN_PATTERN = '[a-f0-9]{12}';
const TOKEN_QUERY = new RegExp(`\\?v=${TOKEN_PATTERN}`, 'g');

/** Remove only release tokens generated by this script so hashing stays stable. */
export function stripAssetVersions(source) {
  return source.replace(TOKEN_QUERY, '');
}

/** Version local CSS and JavaScript loaded directly by an HTML shell. */
export function versionHtmlReferences(source, token) {
  return source.replace(
    /((?:href|src)=["'])((?:\.\.\/)*assets\/(?:css|js)\/[^"'?#]+\.(?:css|js))(?:\?v=[^"'#]+)?(["'])/g,
    `$1$2?v=${token}$3`,
  );
}

/** Version static and dynamic relative imports so the complete module graph refreshes. */
export function versionJavaScriptImports(source, token) {
  return source.replace(
    /((?:from\s+|import\s*\(\s*)["'])(\.[^"'?#]+\.js)(?:\?v=[^"'#]+)?(["'])/g,
    `$1$2?v=${token}$3`,
  );
}

/** Enumerate files in a deterministic order while excluding repository/runtime internals. */
async function walk(directory, accept) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === '.git' || entry.name === 'node_modules') continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await walk(file, accept));
    else if (accept(file)) found.push(file);
  }
  return found.sort();
}

/** Hash normalized browser assets; path names are included to avoid ambiguous concatenation. */
async function releaseToken() {
  const assetRoot = path.join(root, 'assets');
  const files = await walk(assetRoot, file => file.endsWith('.js') || file.endsWith('design-system.css'));
  const hash = createHash('sha256');
  for (const file of files) {
    hash.update(path.relative(root, file).replaceAll('\\', '/'));
    hash.update('\0');
    hash.update(stripAssetVersions(await readFile(file, 'utf8')));
    hash.update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

/** Update or validate every browser entry point without touching data or generated uploads. */
async function main() {
  const checkOnly = process.argv.includes('--check');
  const token = await releaseToken();
  const htmlFiles = await walk(root, file => file.endsWith('.html'));
  const moduleFiles = await walk(path.join(root, 'assets', 'js'), file => file.endsWith('.js'));
  const stale = [];
  for (const file of [...htmlFiles, ...moduleFiles]) {
    const source = await readFile(file, 'utf8');
    const updated = file.endsWith('.html') ? versionHtmlReferences(source, token) : versionJavaScriptImports(source, token);
    if (updated === source) continue;
    stale.push(path.relative(root, file).replaceAll('\\', '/'));
    if (!checkOnly) await writeFile(file, updated, 'utf8');
  }
  if (checkOnly && stale.length) throw new Error(`Run npm run version:assets; stale release token in: ${stale.join(', ')}`);
  process.stdout.write(`${checkOnly ? 'Verified' : 'Applied'} browser asset release ${token}${stale.length ? ` in ${stale.length} files` : ''}.\n`);
}

// Importing this module in tests exposes pure helpers without editing the checkout.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
